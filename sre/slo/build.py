#!/usr/bin/env python3
"""Wrap plain Prometheus rule files (sre/slo/rules/) into PrometheusRule CRs (platform/slo/).

One source of truth: promtool unit-tests the plain file, Argo CD deploys the generated CR.
CI runs this and fails if the output differs from what's committed (`git diff --exit-code`).
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "sre" / "slo" / "rules"
OUT = ROOT / "platform" / "slo"
HEADER = "# GENERATED by sre/slo/build.py from sre/slo/rules/ - edit the source, not this file.\n"


def build() -> list[str]:
    OUT.mkdir(parents=True, exist_ok=True)
    resources = []
    for src in sorted(SRC.glob("*.rules.yaml")):
        name = src.name.removesuffix(".rules.yaml")
        rule = {
            "apiVersion": "monitoring.coreos.com/v1",
            "kind": "PrometheusRule",
            "metadata": {
                "name": name,
                "labels": {"app.kubernetes.io/part-of": "sunn-platform-lab", "role": "slo"},
            },
            "spec": yaml.safe_load(src.read_text()),
        }
        out = OUT / f"{name}.yaml"
        out.write_text(HEADER + yaml.safe_dump(rule, sort_keys=False, width=200))
        resources.append(out.name)

    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "namespace": "monitoring",
        "resources": resources,
    }
    (OUT / "kustomization.yaml").write_text(HEADER + yaml.safe_dump(kustomization, sort_keys=False))
    return resources


if __name__ == "__main__":
    for r in build():
        print(f"wrote platform/slo/{r}")
